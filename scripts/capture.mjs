import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1536, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:5173');
await page.getByRole('button', { name: '첫 던전 입장' }).waitFor();
await page.screenshot({ path: 'test-results/landing.png', fullPage: true });
await page.getByRole('button', { name: '첫 던전 입장' }).click();
await page.waitForTimeout(2300);
await page.screenshot({ path: 'test-results/combat.png', fullPage: true });
await page.keyboard.press('Tab');
await page.screenshot({ path: 'test-results/hint.png', fullPage: true });
await page.keyboard.press('Escape');
await page.getByRole('button', { name: '단어 도감' }).click();
await page.screenshot({ path: 'test-results/codex.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.keyboard.press('Escape');
await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
console.log(JSON.stringify({ errors, screenshots: ['landing', 'combat', 'hint', 'codex', 'mobile'] }));
await browser.close();
